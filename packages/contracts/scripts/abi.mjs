#!/usr/bin/env node
// Writes ts/abi.ts (typed `as const` ABIs for viem/wagmi) from `forge build` output in out/.
//
//   pnpm contracts:build && pnpm contracts:abi          regenerate after a contract change
//   node scripts/abi.mjs --check                         fail if ts/abi.ts is out of date (CI)
//
// Plain Node with no dependencies, so CI's Foundry job can run the check without pnpm install.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'ts', 'abi.ts');

/** Exported name → Foundry artifact (out/<file>/<contract>.json). */
const CONTRACTS = {
  dailyDrawAbi: [
    'DailyDraw.sol',
    'DailyDraw',
    'The game (`src/DailyDraw.sol`), called through its proxy.',
  ],
  devUsdcAbi: [
    'DevUSDC.sol',
    'DevUSDC',
    'Test USDC with a public faucet (`src/dev/DevUSDC.sol`). Its ERC-20 part matches real USDC.',
  ],
  devRandomnessAbi: [
    'DevRandomness.sol',
    'DevRandomness',
    'Hand-triggered randomness for local chains and testnet demos (`src/dev/DevRandomness.sol`).',
  ],
};

function render() {
  const parts = [
    '// Generated by scripts/abi.mjs from `forge build` output. Do not edit by hand:',
    '// run `pnpm contracts:build && pnpm contracts:abi` after changing a contract.',
    '',
  ];
  for (const [name, [file, contract, doc]] of Object.entries(CONTRACTS)) {
    const artifact = join(root, 'out', file, `${contract}.json`);
    let abi;
    try {
      abi = JSON.parse(readFileSync(artifact, 'utf8')).abi;
    } catch (err) {
      throw new Error(
        `Can't read ${artifact}; run \`pnpm contracts:build\` first (${err.message})`,
        { cause: err },
      );
    }
    parts.push(
      `/** ${doc} */`,
      `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;`,
      '',
    );
  }
  return parts.join('\n');
}

const next = render();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== next) {
    console.error('ts/abi.ts is out of date: run `pnpm contracts:build && pnpm contracts:abi`.');
    process.exit(1);
  }
  console.log('ts/abi.ts is up to date.');
} else {
  writeFileSync(target, next);
  console.log(`Wrote ${target}`);
}
